import { describe, expect, it } from 'vitest';
import { composeAddress, findByZip, indexData, parseAddress } from './thaiAddress.js';

const data = indexData([
  ['กรุงเทพมหานคร', [['บางกะปิ', [['หัวหมาก', '10240'], ['คลองจั่น', '10240']]]]],
  ['เชียงใหม่', [['เมืองเชียงใหม่', [['ศรีภูมิ', '50200'], ['สุเทพ', '50200']]], ['สันทราย', [['สันทรายหลวง', '50210']]]]],
]);

describe('ที่อยู่ไทย', () => {
  it('รวมที่อยู่ตามรูปแบบราชการ กรุงเทพฯ ใช้แขวง/เขต', () => {
    expect(composeAddress({ line: '99/1 ถ.รามคำแหง', prov: 'กรุงเทพมหานคร', dist: 'บางกะปิ', sub: 'หัวหมาก', zip: '10240' }))
      .toBe('99/1 ถ.รามคำแหง แขวงหัวหมาก เขตบางกะปิ กรุงเทพมหานคร 10240');
    expect(composeAddress({ line: '1 หมู่ 2', prov: 'เชียงใหม่', dist: 'สันทราย', sub: 'สันทรายหลวง', zip: '50210' }))
      .toBe('1 หมู่ 2 ตำบลสันทรายหลวง อำเภอสันทราย จังหวัดเชียงใหม่ 50210');
  });

  it('แยกที่อยู่ที่ระบบรวมไว้กลับเป็นส่วน ๆ ได้ครบ', () => {
    const p = { line: '1 หมู่ 2', prov: 'เชียงใหม่', dist: 'สันทราย', sub: 'สันทรายหลวง', zip: '50210' };
    expect(parseAddress(composeAddress(p), data)).toEqual(p);
    expect(parseAddress('99/1 ถ.รามคำแหง แขวงหัวหมาก เขตบางกะปิ กรุงเทพมหานคร 10240', data))
      .toEqual({ line: '99/1 ถ.รามคำแหง', prov: 'กรุงเทพมหานคร', dist: 'บางกะปิ', sub: 'หัวหมาก', zip: '10240' });
  });

  it('แยกรูปแบบย่อ ต. อ. จ. ได้ และเติมรหัสไปรษณีย์ให้เมื่อไม่มี', () => {
    expect(parseAddress('5 ต.สุเทพ อ.เมืองเชียงใหม่ จ.เชียงใหม่', data))
      .toEqual({ line: '5', prov: 'เชียงใหม่', dist: 'เมืองเชียงใหม่', sub: 'สุเทพ', zip: '50200' });
  });

  it('ข้อความที่หาจังหวัดไม่เจอเก็บไว้ทั้งหมด ไม่ทำข้อมูลหาย', () => {
    expect(parseAddress('ที่อยู่ต่างประเทศ 12345', data)).toMatchObject({ line: 'ที่อยู่ต่างประเทศ 12345', prov: '' });
  });

  it('ค้นหาตำบลจากรหัสไปรษณีย์', () => {
    expect(findByZip(data, '50200').map((x) => x.sub)).toEqual(['ศรีภูมิ', 'สุเทพ']);
    expect(findByZip(data, '999')).toEqual([]);
  });
});
