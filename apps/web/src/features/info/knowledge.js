const textOf = (a) => [a.title, a.desc, a.summary, ...(a.tags || []), ...a.blocks.map((b) => JSON.stringify(b))].join(' ');

/** เวลาอ่านโดยประมาณจากความยาวข้อความ (ภาษาไทยราว 500 ตัวอักษรต่อนาที) อย่างน้อย 1 นาที */
export const readMinutes = (a) => Math.max(1, Math.round(textOf(a).replace(/[{}"[\],:]/g, '').length / 500));

export const folderOf = (id) => FOLDERS.find((f) => f.id === id);
export const articleOf = (id) => ARTICLES.find((a) => a.id === id);
export const articlesIn = (folderId) => ARTICLES.filter((a) => a.folder === folderId);
export const countIn = (f) => (f.kind === 'faq' ? FAQ.length : f.kind === 'glossary' ? GLOSSARY.length : articlesIn(f.id).length);

/** ค้นหาทั้งบทความ คำถาม และคำศัพท์ คืนผลลัพธ์พร้อมปลายทาง */
export function searchKnowledge(q, cat = 'all') {
  const needle = q.trim().toLowerCase();
  const inCat = (folderId) => cat === 'all' || folderOf(folderId).cat === cat;
  if (!needle) return [];
  const hits = [];
  ARTICLES.forEach((a) => {
    if (!inCat(a.folder)) return;
    const title = a.title.toLowerCase().includes(needle) || (a.tags || []).some((t) => t.toLowerCase().includes(needle));
    if (title || textOf(a).toLowerCase().includes(needle)) {
      hits.push({ key: `a-${a.id}`, kind: 'article', title: a.title, desc: a.desc, folder: a.folder, to: `/guide/${a.folder}/${a.id}`, score: title ? 2 : 1 });
    }
  });
  if (inCat('faq')) {
    FAQ.forEach(([qq, ans], i) => {
      if (`${qq} ${ans}`.toLowerCase().includes(needle)) hits.push({ key: `q-${i}`, kind: 'faq', title: qq, desc: ans, folder: 'faq', to: `/guide/faq#q${i}`, score: 1 });
    });
  }
  if (inCat('glossary')) {
    GLOSSARY.forEach(([term, def], i) => {
      if (`${term} ${def}`.toLowerCase().includes(needle)) hits.push({ key: `g-${i}`, kind: 'term', title: term, desc: def, folder: 'glossary', to: `/guide/glossary#t${i}`, score: term.toLowerCase().includes(needle) ? 2 : 1 });
    });
  }
  return hits.sort((a, b) => b.score - a.score);
}
