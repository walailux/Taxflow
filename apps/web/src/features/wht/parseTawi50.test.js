describe('moneysIn / normalizeText', () => {
  it('อ่านเฉพาะตัวเลขรูปแบบเงิน ไม่สับสนกับวันที่ เลขผู้เสียภาษี หรือเลขแถว', () => {
    expect(moneysIn('2. ตามมาตรา 40 (2) 1 ต.ค. 2569 12,000.00 360.00')).toEqual([12000, 360]);
    expect(moneysIn('0 1055 51234 56 7 และ 01.10.69')).toEqual([]);
    expect(moneysIn('ยอด 1,250,000 บาท')).toEqual([1250000]);
  });
  it('แปลงเลขไทยเป็นเลขอารบิก', () => {
    expect(normalizeText('๑๒,๓๔๕.๖๗')).toBe('12,345.67');
  });
});

describe('detectRate', () => {
  it('หาอัตราจากยอดเงินและภาษีด้วยสูตรเดียวกับตอนบันทึก', () => {
    expect(detectRate(12000, 360)).toBe(3);
    expect(detectRate(10000, 200)).toBe(2);
    expect(detectRate(10000, 333)).toBeNull();
  });
});

describe('parseTawi50', () => {
  it('50 ทวิ ที่ TaxFlow ออก: อ่านครบทุกช่อง', () => {
    const r = parseTawi50(TAXFLOW_PDF);
    expect(r.recognized).toBe(true);
    expect(r.fields.payer.value).toBe('บริษัท มีเดีย เอเจนซี่ จำกัด');
    expect(r.fields.payerTaxId.value).toBe(PAYER_ID);
    expect(r.fields.payerTaxId.note).toBeNull();
    expect(r.fields.payee.value).toBe('นางสาวนุสนีย์ มะแอเคียน');
    expect(r.fields.amount.value).toBe(12000);
    expect(r.fields.wht.value).toBe(360);
    expect(r.fields.rate.value).toBe(3);
    expect(r.fields.incomeType.value).toBe('มาตรา 40(2)');
    expect(r.fields.datePaid.value).toBe('1 ต.ค. 2569');
    expect(r.warnings).toEqual([]);
  });

  it('ข้อความจาก pdf.js ที่สระอาหายและสระอำแยก: ยังหาบล็อกคู่กรณีเจอ และชื่อถูกแก้เป็นสระอำตัวเดียว', () => {
    const r = parseTawi50(PDFJS_ARTIFACTS);
    expect(r.recognized).toBe(true);
    expect(r.fields.payer.value).toBe('บริษัท มีเดีย เอเจนซี่ จำกัด');
    expect(r.fields.payerTaxId.value).toBe(PAYER_ID);
    expect(r.fields.payee.value).toBe('นางสาวนุสนีย์ มะแอเคียน');
    expect(r.fields.datePaid.value).toBe('1 ตุล. 2569');
    expect(r.fields.rate.value).toBe(3);
    expect(r.warnings).toEqual([]);
  });

  it('แบบกรมสรรพากรแถวที่ 5: ไม่เดาประเภทเงินได้ แต่บอกเหตุผลให้ผู้ใช้เลือกเอง', () => {
    const r = parseTawi50(RD_FORM_ROW5);
    expect(r.fields.payer.value).toBe('ห้างหุ้นส่วนจำกัด สตูดิโอ ดี');
    expect(r.fields.amount.value).toBe(25500);
    expect(r.fields.wht.value).toBe(765);
    expect(r.fields.rate.value).toBe(3);
    expect(r.fields.incomeType.value).toBeNull();
    expect(r.fields.incomeType.note).toContain('3 เตรส');
    expect(r.fields.datePaid.value).toBe('15/09/2569');
  });

  it('ข้อความจาก OCR ที่มีช่องว่างกลางคำและเลขไทย', () => {
    const r = parseTawi50(OCR_TEXT);
    expect(r.recognized).toBe(true);
    expect(r.fields.payer.value).toBe('บริษัท ครีเอทีฟ ฮับ จำกัด');
    expect(r.fields.amount.value).toBe(8000);
    expect(r.fields.wht.value).toBe(240);
    expect(r.fields.rate.value).toBe(3);
    expect(r.fields.incomeType.value).toBe('มาตรา 40(2)');
  });

  it('ภาษีไม่ตรงอัตราที่ระบบรองรับ: ไม่กรอกอัตราและเตือนให้ตรวจ', () => {
    const r = parseTawi50(TAXFLOW_PDF.replaceAll('360.00', '333.00'));
    expect(r.fields.rate).toBeUndefined();
    expect(r.warnings.join(' ')).toContain('ไม่ตรงกับอัตราที่ระบบรองรับ');
  });

  it('เลขผู้เสียภาษีที่หลักสุดท้ายไม่ถูกต้อง: ยังแสดงแต่เตือนว่าอาจอ่านผิด', () => {
    const wrong = PAYER_ID.slice(0, 12) + String((Number(PAYER_ID[12]) + 1) % 10);
    const r = parseTawi50(TAXFLOW_PDF.replace(PAYER_ID.split('').join(' '), wrong));
    expect(r.fields.payerTaxId.value).toBe(wrong);
    expect(r.fields.payerTaxId.note).toContain('อาจอ่านตัวเลขผิด');
  });

  it('ไฟล์ที่ไม่ใช่ 50 ทวิ: ไม่กรอกอะไรและเตือนให้ตรวจไฟล์', () => {
    const r = parseTawi50('ใบเสนอราคา\nรวมทั้งสิ้น 5,000.00');
    expect(r.recognized).toBe(false);
    expect(r.fields.payer).toBeUndefined();
    expect(r.warnings[0]).toContain('ไม่พบหัวเรื่อง');
  });
});

